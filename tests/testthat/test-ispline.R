test_that("I-splines rise from 0 to 1 and are non-decreasing", {
  eta <- seq(-4, 4, 0.05)
  I <- ispline_basis(eta, ispline_knots(2), order = 2)
  expect_equal(ncol(I), 2 + 2)
  expect_true(all(I >= -1e-12 & I <= 1 + 1e-12))
  expect_true(all(apply(I, 2, diff) >= -1e-12))
  expect_equal(unname(I[1, ]), rep(0, 4))
  expect_equal(unname(I[nrow(I), ]), rep(1, 4))
  expect_equal(ispline_basis(c(-6, 6)), ispline_basis(c(-4, 4)))
  expect_equal(ispline_knots(1), 0)
})

test_that("the I-spline curve object equals beta0 - I a", {
  interior <- ispline_knots(3); a <- c(2, 0, 5, 1, 3)
  act <- ispline_act(caliber:::ispline_beta(80, a), interior, 2, NA, c(log(6), 0))
  eta <- seq(-4, 4, 0.1)
  expect_equal(mu_sqi(eta, act), 80 - drop(ispline_basis(eta, interior, 2) %*% a))
  expect_true(all(diff(mu_sqi(eta, act)) <= 1e-12))
  expect_equal(act$type, "ispline")
})

test_that("fit_ms(curve = \"ispline\") recovers the sleep curve", {
  d <- sleep_data(); Y <- as.matrix(d[paste0("C", 1:7)])
  grm <- fit_grm(Y)
  f <- fit_ms(grm, Y, d$SQI, "fixed", curve = "ispline", n_knots = 1)
  expect_true(f$converged)
  expect_equal(f$curve, "ispline")
  expect_equal(f$n_knots, 1)
  expect_true(all(diff(mu_sqi(seq(-4, 4, 0.1), f$act)) <= 1e-8))
  expect_lt(abs(f$act$sigma - 6), 0.6)
  expect_lt(abs(mu_sqi(0, f$act) - 72), 2)
  expect_true(all(f$coef[-1] >= 0))
  thr <- threshold_locations(f$a, f$d, f$act)
  expect_equal(dim(thr$sqi), c(7, 3))
  vc <- ms_vcov(f, Y, d$SQI)
  expect_equal(dim(vc$V_beta), rep(length(f$act$beta), 2))
  iv <- ms_intervals(f, vc, function(a, d, act) c(mu0 = mu_sqi(0, act)), n_draw = 50, seed = 1)
  expect_true(iv$lo <= iv$est && iv$est <= iv$hi)
})

test_that("the knot number is chosen by AIC and the EAP and joint modes run", {
  d <- sleep_data(); Y <- as.matrix(d[paste0("C", 1:7)])
  grm <- fit_grm(Y)
  e <- fit_ms(grm, Y, d$SQI, "eap", curve = "ispline", max_knots = 3)
  expect_equal(e$path$n_knots, 0:3)
  expect_equal(e$n_knots, e$path$n_knots[which.min(e$path$aic)])
  j <- fit_ms(grm, Y, d$SQI, "joint", curve = "ispline", n_knots = 1)
  expect_true(j$converged)
  expect_false(isTRUE(all.equal(j$a, grm$a)))
})
